"""Общие настройки валидации Dishka-контейнеров в тестах.

Флаги Dishka называются «наоборот»: включённый флаг означает «проверять это
нарушение», а не «разрешить такое поведение». Поэтому строгий набор —
это все флаги в True.
"""

from dishka import ValidationSettings

# Строгая валидация графа: конфликты фабрик ловятся при создании контейнера,
# а не в рантайме. Иначе тест может оказаться ложно-зелёным — например, если
# фейк молча не переопределил прод-провайдер или провайдеры конфликтуют.
VALIDATION_SETTINGS = ValidationSettings(
    implicit_override=True,
    nothing_overridden=True,
    nothing_decorated=True,
)
